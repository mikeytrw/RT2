// Build a path under the checked-in fixture directory.
std::filesystem::path FixtureDir()
{
    return std::filesystem::current_path() / "RT2App" / "assets" / "phase1a-fixtures";
}

// Write a string to a temp file and return its path.
std::filesystem::path WriteTempFile(const std::string& content,
                                    const std::string& suffix = ".rt2scene")
{
    auto dir = std::filesystem::temp_directory_path();
    auto path = dir / ("rt2_p1a_" + std::to_string(std::rand()) + suffix);
    std::ofstream out(path, std::ios::binary | std::ios::trunc);
    out.write(content.data(), static_cast<std::streamsize>(content.size()));
    out.close();
    return path;
}

